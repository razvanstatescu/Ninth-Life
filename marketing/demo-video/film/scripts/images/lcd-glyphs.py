"""Bitmap glyphs for Act 1's 96 x 64 phone screen (research-v2/10-act1-old-world.md, section 3.2).

Rasterises printable ASCII from two SIL OFL pixel fonts at their native sizes into 1-bit glyphs, so the film
stamps exact pixels on the LCD grid without loading fonts at render time:
- "small": Tiny5 (The Tiny5 Project Authors) at 8 px: capitals on rows 2-6 of the origin, descender row 7;
- "large": Departure Mono (Helena Zhang) at 11 px: capitals on rows 3-10, descenders rows 11-12.

    python3 -I scripts/images/lcd-glyphs.py <Tiny5.ttf> <DepartureMono.otf>      (from film/)

Writes src/components/act1/v2/lcd-glyphs.json. Both fonts are OFL 1.1 with no Reserved Font Name; the
licence text and the copyright notices are in src/components/act1/v2/LICENSE-lcd-glyphs.txt.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / 'src' / 'components' / 'act1' / 'v2' / 'lcd-glyphs.json'
PAD = 3


def glyphs(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    rows_h = ascent + descent + 1
    out = {}
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        w = adv + 2 * PAD
        im = Image.new('1', (w, rows_h), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = '1'
        d.text((PAD, 0), ch, font=font, fill=1)
        bb = im.getbbox()
        if not bb:
            out[ch] = {'adv': adv, 'x': 0, 'y': 0, 'rows': []}
            continue
        x0, y0, x1, y1 = bb
        rows = []
        for y in range(y0, y1):
            rows.append(''.join('1' if im.getpixel((x, y)) else '0' for x in range(x0, x1)))
        out[ch] = {'adv': adv, 'x': x0 - PAD, 'y': y0, 'rows': rows}
    return {'size': size, 'ascent': ascent, 'descent': descent, 'glyphs': out}


def main():
    tiny, dep = sys.argv[1], sys.argv[2]
    data = {
        '_about': 'Generated by scripts/images/lcd-glyphs.py. Glyph rows are 1-bit, from the text origin (PIL): '
                  'a glyph covers rows y.. and columns x.. relative to the pen position; advance in px. '
                  'small = Tiny5 8 px, large = Departure Mono 11 px. Both SIL OFL 1.1 (LICENSE-lcd-glyphs.txt).',
        'small': glyphs(tiny, 8),
        'large': glyphs(dep, 11),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, separators=(',', ':')) + '\n')
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
