#!/usr/bin/env node
// Generates styles/tokens.css from design/system/tokens.json.
//
// Output:
//   :root, [data-theme="night"]  night values (Night is the default theme and the brand)
//   [data-theme="day"]           day values
//   @media (prefers-color-scheme: light) { [data-theme="system"] } day values
// Color and shadow `{alias}` values are resolved per theme. Type styles become
// --type-<name>-* custom properties plus .nl-type-<name> helper classes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS = resolve(here, '../../../design/system/tokens.json');
const OUT = resolve(here, '../styles/tokens.css');

/**
 * Values the brand book states in prose but tokens.json does not carry.
 * Kept here, next to the generator, so every theme value lives in one generated file.
 */
const DERIVED = {
  night: {
    'color-scheme': 'dark',
    // Day draws a plum ring inside ember fills (ember is 1.7:1 on the Day ground).
    'ember-edge': '0 0 0 0 transparent',
  },
  day: {
    'color-scheme': 'light',
    'ember-edge': 'inset 0 0 0 3px #2a1856',
  },
};

/** Resolve `{name}` references against a flat map for one theme. */
export function resolveAlias(value, theme, table, seen = new Set()) {
  if (typeof value !== 'string') return value;
  return value.replace(/\{([a-z0-9-]+)\}/gi, (_, name) => {
    if (seen.has(name)) throw new Error(`Circular token alias: ${[...seen, name].join(' -> ')}`);
    const entry = table[name];
    if (entry === undefined) throw new Error(`Unknown token alias {${name}}`);
    const raw = typeof entry === 'object' ? entry[theme] : entry;
    return resolveAlias(raw, theme, table, new Set([...seen, name]));
  });
}

function px(v) {
  return typeof v === 'number' ? String(v) : v;
}

/** Build the CSS text. Pure, so tests can call it. */
export function buildTokensCss(tokens) {
  const themes = tokens.color.themes.map((t) => t.id);
  if (!themes.includes('night') || !themes.includes('day')) {
    throw new Error('tokens.json must define night and day themes');
  }

  const colorTable = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
  const shadowTable = Object.fromEntries((tokens.shadow?.tokens ?? []).map((t) => [t.name, t.value]));
  const table = { ...colorTable, ...shadowTable };

  const themeBlock = (theme) => {
    const lines = [];
    for (const t of tokens.color.tokens) {
      lines.push(`  --${t.name}: ${resolveAlias(typeof t.value === 'object' ? t.value[theme] : t.value, theme, table)};`);
    }
    for (const t of tokens.shadow?.tokens ?? []) {
      lines.push(`  --${t.name}: ${resolveAlias(typeof t.value === 'object' ? t.value[theme] : t.value, theme, table)};`);
    }
    for (const [k, v] of Object.entries(DERIVED[theme] ?? {})) {
      if (k === 'color-scheme') lines.push(`  color-scheme: ${v};`);
      else lines.push(`  --${k}: ${v};`);
    }
    return lines.join('\n');
  };

  const shared = [];
  shared.push(`  --font-sans: ${tokens.type.families.sans};`);
  shared.push(`  --font-mono: ${tokens.type.families.mono};`);
  for (const group of ['spacing', 'size', 'radius']) {
    for (const t of tokens[group]?.tokens ?? []) shared.push(`  --${t.name}: ${t.value};`);
  }
  const typeClasses = [];
  for (const g of tokens.type.groups) {
    for (const s of g.styles) {
      const fam = `var(--font-${g.family})`;
      shared.push(`  --type-${s.name}-size: ${s.fontSize};`);
      shared.push(`  --type-${s.name}-line: ${px(s.lineHeight)};`);
      shared.push(`  --type-${s.name}-weight: ${s.fontWeight};`);
      if (s.letterSpacing) shared.push(`  --type-${s.name}-tracking: ${s.letterSpacing};`);
      typeClasses.push(
        `.nl-type-${s.name} { font-family: ${fam}; font-size: var(--type-${s.name}-size); line-height: var(--type-${s.name}-line); font-weight: var(--type-${s.name}-weight);${
          s.letterSpacing ? ` letter-spacing: var(--type-${s.name}-tracking);` : ''
        } }`,
      );
    }
  }

  return `/* Generated by scripts/gen-tokens.mjs from design/system/tokens.json. Do not edit by hand. */

:root {
${shared.join('\n')}
}

:root,
[data-theme="night"] {
${themeBlock('night')}
}

[data-theme="day"] {
${themeBlock('day')}
}

@media (prefers-color-scheme: light) {
  [data-theme="system"] {
${themeBlock('day')
  .split('\n')
  .map((l) => `  ${l}`)
  .join('\n')}
  }
}

${typeClasses.join('\n')}
`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const tokens = JSON.parse(readFileSync(TOKENS, 'utf8'));
  const css = buildTokensCss(tokens);
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, css);
  console.log(`gen-tokens: wrote ${OUT}`);
}
